void display_hand_graphics(int hand[][3], int count, const char *name, int deckCount, int x_start, int y_start) {
    const char *faces[] = {"2", "3", "4", "5", "6", "7", "8", "9", "10", "Jack", "Queen", "King", "Ace"};
    const char *suits[] = {"Hearts", "Diamonds", "Clubs", "Spades"};
    int card_spacing = 50; // Space between cards

    gfx_color(0, 0, 0);

    // Loop through the hand to draw each card
    for (int i = 0; i < count; i++) {
        int suit = hand[i][0];
        int value = hand[i][1];

        // Calculate card position
        int x = x_start + i * card_spacing;
        int y = y_start;

        // Draw card
        draw_card(x, y, value, suit);
    }
    // Calculate total and display it
    int total = calc_total(hand, count);
    char total_label[30];
    sprintf(total_label, "%s's Total: %d", name, total);
    gfx_color(0, 0, 0);
    gfx_text(total_label, x_start-2, y_start+1 + 220, 1);
    gfx_color(255, 255, 255);
    gfx_text(total_label, x_start, y_start + 220, 1);
}

