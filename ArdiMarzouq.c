// -----------------------------------------------------------------------------------------------------------

int calc_total(int hand[][3], int count) {
    int total = 0;
    int aces = 0;

    for (int i = 0; i < count; i++) {
        total += hand[i][2];  // Add the value of the card
        if (hand[i][2] == 11) {  // Check for Ace
            aces++;
        }
    }

    // Adjust for Aces if total exceeds 21
    while (total > 21 && aces > 0) {
        total -= 10;
        aces--;
    }

    return total;
}

