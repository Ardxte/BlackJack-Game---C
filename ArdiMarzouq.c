void shuffle_deck(int deck[MAX_DECK][3]) {
    for (int i = 0; i < MAX_DECK; i++) {
        int j = rand() % MAX_DECK;

        // Swap cards i and j
        for (int k = 0; k < 3; k++) { // Swap all attributes (suit, rank, value)
            int temp = deck[i][k];
            deck[i][k] = deck[j][k];
            deck[j][k] = temp;
        }
    }
}


